from __future__ import annotations

import json
from datetime import datetime
from io import StringIO

import pandas as pd

from src.ui.schema import FrontendCandidate

_DISCLAIMER = """
---
## Scientific Limitation

TargetForge outputs are computational hypotheses generated under a hackathon
demonstration context. Activity scores are deterministic hash-based demo values,
not real machine-learning predictions. Docking scores are fallback estimates,
not real AutoDock Vina / Glide / DOCK outputs. Novelty scores are hardcoded demo
constants (0.5 for all candidates). This report does not establish safety, efficacy,
clinical benefit, or regulatory approval of any molecule. Laboratory validation is
required before drawing any scientific conclusions.

Generated by TargetForge (hackathon prototype).
"""

_TIMESTAMP = lambda: datetime.now().strftime("%Y-%m-%d %H:%M:%S")


# ---------------------------------------------------------------------------
# CSV exports
# ---------------------------------------------------------------------------

def build_ranking_csv(candidates: list[FrontendCandidate]) -> str:
    """Flat CSV of the FrontendCandidate ranking list."""
    if not candidates:
        return "No candidates to export."
    rows = []
    for c in candidates:
        rows.append({
            "rank":              c.rank,
            "compound_id":       c.candidate_id,
            "smiles":            c.smiles,
            "source":            c.source,
            "activity_score":    c.activity_score,
            "activity_score_note": "deterministic_demo" if c.is_demo else "real",
            "predicted_class":   c.predicted_class,
            "model_version":     c.model_version,
            "mw":                c.properties.mw,
            "logp":              c.properties.logp,
            "hbd":               c.properties.hbd,
            "hba":               c.properties.hba,
            "tpsa":              c.properties.tpsa,
            "rotatable_bonds":   c.properties.rotatable_bonds,
            "property_score":    c.property_score,
            "filter_status":     c.filter.status,
            "filter_reasons":    "; ".join(c.filter.reasons),
            "docking_score_raw": c.docking.score_raw,
            "docking_score_note": "FALLBACK_DEMO" if c.is_demo else "real",
            "docking_score_normalized": c.docking.score_normalized,
            "receptor_id":       c.docking.receptor_id,
            "docking_status":    c.docking.docking_status,
            "novelty_score":     c.novelty_score,
            "novelty_score_note": "hardcoded_0.5_demo" if c.is_demo else "real",
            "final_score":       c.final_score,
            "status":            c.status,
            "is_demo":           c.is_demo,
        })
    buf = StringIO()
    pd.DataFrame(rows).to_csv(buf, index=False)
    return buf.getvalue()


def build_validated_csv(validated_df: pd.DataFrame | None) -> str:
    """CSV of the validated molecules DataFrame."""
    if validated_df is None or validated_df.empty:
        return "No validated molecules to export."
    buf = StringIO()
    validated_df.to_csv(buf, index=False)
    return buf.getvalue()


