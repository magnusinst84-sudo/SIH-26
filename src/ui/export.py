def build_summary_json(state: dict) -> str:
    """Structured JSON of session metadata and candidate list."""
    target    = state.get("tf_target")      or {}
    weights   = state.get("tf_weights")     or {}
    filter_cfg = state.get("tf_filter_config") or {}
    candidates = state.get("tf_candidates") or []

    payload = {
        "report_generated_at": _TIMESTAMP(),
        "is_demo_mode":        state.get("tf_demo_mode", True),
        "scientific_note":     (
            "All scores are computational estimates from a hackathon demo. "
            "Not validated scientific results."
        ),
        "target": {
            "name":         target.get("name"),
            "aliases":      target.get("aliases"),
            "structure_id": target.get("structure_id"),
            "disease":      target.get("disease"),
        },
        "model": {
            "version": target.get("model_version"),
            "type":    target.get("model_type"),
        },
        "ranking_weights":   weights,
        "filter_thresholds": filter_cfg,
        "candidates": [
            {
                "rank":            c.rank,
                "candidate_id":    c.candidate_id,
                "smiles":          c.smiles,
                "activity_score":  c.activity_score,
                "activity_note":   "deterministic_demo" if c.is_demo else "real",
                "docking_score":   c.docking.score_raw,
                "docking_note":    "FALLBACK_DEMO"      if c.is_demo else "real",
                "property_score":  c.property_score,
                "novelty_score":   c.novelty_score,
                "novelty_note":    "hardcoded_0.5_demo" if c.is_demo else "real",
                "final_score":     c.final_score,
                "filter_status":   c.filter.status,
                "filter_reasons":  c.filter.reasons,
                "properties": {
                    "mw":              c.properties.mw,
                    "logp":            c.properties.logp,
                    "hbd":             c.properties.hbd,
                    "hba":             c.properties.hba,
                    "tpsa":            c.properties.tpsa,
                    "rotatable_bonds": c.properties.rotatable_bonds,
                },
                "is_demo": c.is_demo,
            }
            for c in candidates
        ],
    }
    return json.dumps(payload, indent=2, default=str)
